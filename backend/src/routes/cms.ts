import { Router } from 'express';
import path from 'node:path';
import { prisma } from '../lib/prisma';
import { AppError } from '../utils/AppError';
import { CONTENT_UPLOAD_ROOT } from '../lib/upload';

export const cmsRoutes = Router();

// Get homepage sections
cmsRoutes.get('/homepage', async (_req, res) => {
  const sections = await prisma.cmsContent.findMany({
    where: { type: { in: ['homepage', 'hero'] }, isActive: true, OR: [{ publishAt: null }, { publishAt: { lte: new Date() } }] },
    orderBy: { createdAt: 'asc' },
  });
  
  res.json({ sections });
});

// Get page content by key
cmsRoutes.get('/page/:key', async (req, res) => {
  const { key } = req.params;
  
  const content = await prisma.cmsContent.findUnique({
    where: { key, isActive: true, OR: [{ publishAt: null }, { publishAt: { lte: new Date() } }] },
  });
  
  if (!content) throw new AppError('Page not found', 404, 'NOT_FOUND');
  
  res.json({ content });
});

// Get content by type
cmsRoutes.get('/type/:type', async (req, res) => {
  const { type } = req.params;
  
  const contents = await prisma.cmsContent.findMany({
    where: { type, isActive: true, OR: [{ publishAt: null }, { publishAt: { lte: new Date() } }] },
    orderBy: { createdAt: 'asc' },
  });
  
  res.json({ contents });
});

// Get lookbook
cmsRoutes.get('/lookbook', async (_req, res) => {
  const lookbook = await prisma.cmsContent.findMany({
    where: { type: 'lookbook', isActive: true },
    orderBy: { createdAt: 'desc' },
  });
  
  res.json({ lookbook });
});

// Names are generated by the uploader, so an exact shape is enough to keep this
// route inside uploads/content and unreachable for anything else on disk.
const CONTENT_MEDIA_NAME = /^content-[0-9a-z-]+\.(?:jpg|jpeg|png|webp|avif|mp4|webm)$/;

/**
 * Public read for the images and clips an admin publishes as storefront
 * content. sendFile answers Range requests, so a clip can be scrubbed.
 */
cmsRoutes.get('/media/:filename', (req, res) => {
  const filename = String(req.params.filename || '');
  if (!CONTENT_MEDIA_NAME.test(filename)) {
    throw new AppError('File not found', 404, 'NOT_FOUND');
  }

  const file = path.join(CONTENT_UPLOAD_ROOT, filename);
  if (!file.startsWith(CONTENT_UPLOAD_ROOT)) {
    throw new AppError('File not found', 404, 'NOT_FOUND');
  }

  // Upload names are unique per file, so a published asset never changes.
  res.setHeader('Cache-Control', 'public, max-age=31536000, immutable');
  res.sendFile(file, (err) => {
    if (err && !res.headersSent) {
      res.status(404).json({ error: 'File not found', code: 'NOT_FOUND' });
    }
  });
});